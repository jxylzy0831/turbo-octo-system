def main():
    revised = []
    for scene_index, (title, subtitle, rows) in enumerate(source.SCENES):
        edits = SPEECH[scene_index]
        out = []
        for row_index, (who, text) in enumerate(rows):
            if who in source.KEYS:
                # 生成时遇到未重写的演员台词便停止，避免新旧声线混用。
                text = edits[row_index]
            else:
                for before, after in NOTE_CHANGES.items():
                    text = text.replace(before, after)
            out.append((who, text.replace('—', '至').replace('–', '至')))
        revised.append((title, subtitle.replace('—', '至'), out))
    source.SCENES = revised
    source.BASE = BASE
    source.OUTDIR = ROOT / 'drafts/末日学校/第一幕互动/历史版本'
    source.main()
    for suffix in ('.md', '.html'):
        path = source.OUTDIR / (BASE + suffix)
        text = path.read_text(encoding='utf-8')
        text = text.replace('长时版 v3', '自然对白版 v4').replace('长时版</title>', '自然对白版 v4</title>')
        text = text.replace('今天的学校，先由我们一起办起来。', '来都来了，先坐下说。')
        text = text.replace('60—75', '60至75').replace('N1—N4', 'N1 至 N4')
        text = text.replace('末日学校-第一幕长时互动设计说明-20261002-v3.md', '末日学校-第一幕自然对白改写说明-20261002-v4.md')
        if suffix == '.md':
            text = text.replace('原创排练稿。', '按 human-writing 重写的原创排练稿。', 1)
        path.write_text(text, encoding='utf-8')
    print('已生成自然对白版 v4，原长时版 v3 保留。')


if __name__ == '__main__':
    main()
