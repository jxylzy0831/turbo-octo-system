def main():
    scenes = []
    for si, (title, subtitle, rows) in enumerate(source.SCENES):
        revised = []
        for ri, (who, original) in enumerate(rows):
            text = v4.SPEECH[si][ri] if who in source.KEYS else original
            if who not in source.KEYS:
                for before, after in v4.NOTE_CHANGES.items():
                    text = text.replace(before, after)
            text = EDITS.get((si, ri), text)
            revised.append((who, text.replace('—', '至').replace('–', '至')))
            revised.extend(AFTER.get((si, ri), []))
        scenes.append((title, subtitle.replace('—', '至'), revised))
    source.SCENES = scenes
    source.BASE = BASE
    source.OUTDIR = ROOT / 'drafts/末日学校/第一幕互动/当前稿'
    source.main()
    for suffix in ('.md', '.html'):
        path = source.OUTDIR / (BASE + suffix)
        text = path.read_text(encoding='utf-8')
        text = text.replace('长时版 v3', 'G 人物深化版 v5').replace('长时版</title>', 'G 人物深化版 v5</title>')
        text = text.replace('今天的学校，先由我们一起办起来。', '我也坐这儿，行吗？')
        text = text.replace('60—75', '60至75').replace('N1—N4', 'N1 至 N4')
        text = text.replace('末日学校-第一幕长时互动设计说明-20261002-v3.md', '末日学校-第一幕G人物深化说明-20261002-v5.md')
        if suffix == '.md':
            text = text.replace('原创排练稿。', '沿用 human-writing 自然对白，以动作与回应深化 G 的原创排练稿。', 1)
        else:
            text = text.replace('时间、声光与互动设计说明</a>', 'G 人物深化说明与原舞台安排</a>')
        path.write_text(text, encoding='utf-8')
    print('已生成 G 人物深化版 v5，v3、v4 原文件保留。')


if __name__ == '__main__':
    main()
