def markdown(s):
    lines=s.splitlines(); out=[]; para=[]; inlist=False
    def flush():
        if para:
            out.append('<p>'+html.escape(' '.join(para))+'</p>'); para.clear()
    for line in lines:
        if not line.strip():
            flush()
            if inlist:out.append('</ul>');inlist=False
        elif line.startswith('#'):
            flush()
            if inlist:out.append('</ul>');inlist=False
            n=min(len(line)-len(line.lstrip('#'))+1,4)
            out.append(f'<h{n}>'+html.escape(line.lstrip('# '))+f'</h{n}>')
        elif line.startswith('- '):
            flush()
            if not inlist:out.append('<ul>');inlist=True
            out.append('<li>'+html.escape(line[2:])+'</li>')
        else:para.append(line)
    flush()
    if inlist:out.append('</ul>')
    return '\n'.join(out)

