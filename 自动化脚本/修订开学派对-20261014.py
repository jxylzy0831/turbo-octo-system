def replace_once(text, old, new, label):
    if text.count(old) != 1:
        raise ValueError(f'{label}应命中一次，实际{text.count(old)}次')
    return text.replace(old, new, 1)


def main():
    pending = []
    records = []
    for name, old_version, new_version in [('恩书', 5, 6), ('知夏', 3, 4), ('多允', 3, 4), ('瑞真', 3, 4)]:
        source = ROOT / f'草稿/{name}-人物本-20261014-重写第{old_version}版.md'
        target = ROOT / f'草稿/{name}-人物本-20261014-重写第{new_version}版.md'
        if target.exists():
            raise FileExistsError(target)
        original = source.read_text(encoding='utf-8-sig')
        revised = replace_once(original, OLD_PROLOGUE, NEW_PROLOGUE, name + '序幕')
        revised = replace_once(revised, *CHANGES[name], name + '第二幕')
        revised = replace_once(revised, '## 第二幕 开学\n', '## 第二幕 开学派对\n', name + '幕名')
        revised = revised.replace('小聚', '派对')
        if name == '知夏':
            revised = replace_once(
                revised,
                '你站在门口，说邀请给他本人，他会停一下，再答应时间。',
                '你去校医室登记，临走说给他留个位置，他看过交接时间，答应值完班就来。',
                name + '第五幕回忆',
            )
        pending.append((target, revised))
        records.append({
            '角色': name,
            '旧稿': str(source.relative_to(ROOT)),
            '新稿': str(target.relative_to(ROOT)),
            '旧稿sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
            '旧稿汉字': len(re.findall(r'[\u4e00-\u9fff]', original)),
            '新稿汉字': len(re.findall(r'[\u4e00-\u9fff]', revised)),
        })
    QA.mkdir(parents=True, exist_ok=True)
    for target, revised in pending:
        with target.open('x', encoding='utf-8', newline='\n') as handle:
            handle.write(revised)
    (QA / '春日新旧稿字数与来源.json').write_text(json.dumps(records, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    for record in records:
        print(record['新稿'], record['新稿汉字'])


if __name__ == '__main__':
    main()
