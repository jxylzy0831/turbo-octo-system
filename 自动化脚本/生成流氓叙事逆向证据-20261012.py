        links = []
        for name, start, end in refs:
            path = BASE / (name + ".txt")
            if name not in cache:
                cache[name] = []
                for line_num, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
                    match = re.match(r"^\[(\d+)\] (.*)$", line)
                    if match:
                        cache[name].append([line_num, int(match[1]), match[2]])
                    elif cache[name]:
                        cache[name][-1][2] += "\n" + line
            selected = [(line_num, paragraph, content) for line_num, paragraph, content in cache[name]
                        if start <= paragraph <= end]
